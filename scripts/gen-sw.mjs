// Runs after `next build`. Writes out/sw.js with the list of every built file,
// so the whole app is saved for offline use on the first visit.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const OUT = join(process.cwd(), 'out');

function walk(dir) {
  const files = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) files.push(...walk(full));
    else files.push(full);
  }
  return files;
}

const hash = createHash('sha256');
const urls = [];
let bytes = 0;
for (const file of walk(OUT).sort()) {
  const rel = relative(OUT, file).split(sep).join('/');
  if (rel === 'sw.js' || rel.endsWith('.map')) continue;
  const data = readFileSync(file);
  hash.update(rel).update(data);
  bytes += data.length;
  // Pages are served at their folder URL ("/student/"), matching trailingSlash.
  if (rel === 'index.html') urls.push('/');
  else if (rel.endsWith('/index.html')) urls.push('/' + rel.slice(0, -'index.html'.length));
  else if (rel === '404.html' || rel.startsWith('404/')) continue;
  else urls.push('/' + rel);
}
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/gen-sw.mjs. Do not edit.
const CACHE = 'heargraph-${version}';
const URLS = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) =>
      Promise.all(URLS.map((url) => cache.add(new Request(url, { cache: 'reload' })).catch(() => undefined))),
    ).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('heargraph-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      // Query strings (?sample=cart) do not change which file is served.
      const cached = await cache.match(request, { ignoreSearch: true });
      if (request.mode === 'navigate') {
        // Pages: try the network first so a new version shows up straight away,
        // but fall back to the saved copy when offline or after 3 seconds.
        try {
          const fresh = await Promise.race([
            fetch(request),
            new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), cached ? 3000 : 30000)),
          ]);
          if (fresh.ok || !cached) return fresh;
        } catch (err) {
          if (!cached) {
            const home = await cache.match('/');
            if (home) return home;
            throw err;
          }
        }
        return cached;
      }
      // Scripts and styles have a content hash in their name, so the saved copy is always right.
      return cached || fetch(request);
    }),
  );
});
`;
writeFileSync(join(OUT, 'sw.js'), sw);
console.log(`sw.js written: ${urls.length} files, ${(bytes / 1024).toFixed(0)} KB uncompressed, cache heargraph-${version}`);
